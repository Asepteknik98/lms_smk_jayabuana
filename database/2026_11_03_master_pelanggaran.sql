CREATE TABLE IF NOT EXISTS kredit_master_pelanggaran (
 id int unsigned NOT NULL AUTO_INCREMENT,
 kode varchar(20) NOT NULL,
 kategori char(1) NOT NULL,
 nama varchar(500) NOT NULL,
 poin int unsigned NOT NULL,
 penanganan varchar(500) DEFAULT NULL,
 aktif tinyint(1) NOT NULL DEFAULT 1,
 urutan int unsigned NOT NULL DEFAULT 0,
 diubah_oleh int unsigned DEFAULT NULL,
 updated_at timestamp NOT NULL DEFAULT current_timestamp() ON UPDATE current_timestamp(),
 PRIMARY KEY(id), UNIQUE KEY uq_kps_master_kode(kode), KEY idx_kps_master_kategori(aktif,kategori,urutan),
 CONSTRAINT fk_kps_master_admin FOREIGN KEY(diubah_oleh) REFERENCES users(id) ON DELETE SET NULL,
 CONSTRAINT chk_kps_master_poin CHECK(poin BETWEEN 1 AND 100000),
 CONSTRAINT chk_kps_master_kategori CHECK(kategori IN ('A','B','C','D','E','F','G','H','I','J','K'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

